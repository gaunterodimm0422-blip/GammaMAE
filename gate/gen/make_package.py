#!/usr/bin/env python3
"""Generate the GammaMAE-v2 GATE package (macros, job list).

  * bare crystals in air, same geometry as v1 (NaI 3"x3", HPGe 5x5 cm, GAGG 1"x1")
  * every gamma / K x-ray line (I >= 1 %, E >= 10 keV, ENSDF via IAEA LiveChart)
    is an independent Mono point source; activity = 37 kBq * I * f(theta),
    f = (1-cos theta)/2, theta = atan(r/d) + 2 deg covers the whole front face
    -> simulated time == real measurement time
  * source-to-front-face distance d = 5, 10, 25 cm; 600 s per seed, 3 seeds
  * ambient background: K/U/Th primary lines (soil half-space unscattered weights)
    + one smooth down-scattered continuum, emitted inward (cos-law) from a sphere
    around the crystal -> isotropic uniform field.  Mixed in post-processing.
"""
import json, math, os, shutil
import numpy as np, pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
LD = os.path.join(HERE, "linedata")
OUT = os.environ.get("GMAE_OUT", os.path.dirname(HERE))   # default: package root (gen/..)

ACT = 37000.0
T_MEAS = 600
SEEDS = [0, 1, 2]
DISTS = [5, 10, 25]
MARGIN_DEG = 2.0
MAX_ENTER_PER_CHUNK = float(os.environ.get("MAX_ENTER_PER_CHUNK", 6.0e5))
CHUNK_CHOICES = [600, 300, 200, 150, 120, 100, 60, 50, 40, 30, 20, 10]

DET = {  # name: (volume, material, Rmax cm, H cm, cut mm)
    "NaI":  ("NaI_crystal",  "NaITl",     3.81, 7.62, 0.1),
    "GAGG": ("GAGG_crystal", "GAGG_Ce",   1.27, 2.54, 0.1),
    "HPGe": ("HPGe_crystal", "Germanium", 2.50, 5.00, 0.1),
}
NUC = {"Am241": "241am", "Ba133": "133ba", "Co57": "57co", "Co60": "60co",
       "Cs137": "137cs", "Eu152": "152eu", "I131": "131i", "K40": "40k",
       "Mn54": "54mn", "Na22": "22na"}

def lines(key, emin=10.0, imin=1.0, xrays=True):
    out = []
    for suf in (["", "_x"] if xrays else [""]):
        f = os.path.join(LD, key + suf + ".csv")
        if not os.path.exists(f):
            continue
        d = pd.read_csv(f)
        d = d[pd.to_numeric(d.p_energy, errors="coerce").fillna(0) == 0]   # ground-state parent only
        d = d[d.decay.astype(str) != "IT"]
        if suf == "":   # gamma files also list x-rays (no level info); keep true gammas + annihilation
            d = d[d.start_level_energy.notna() | (d.energy.round(0) == 511)]
        d = d[(d.energy >= emin) & (d.intensity >= imin)]
        for _, r in d.iterrows():
            out.append((float(r.energy), float(r.intensity) / 100.0, "x" if suf else "g"))
    out.sort()
    merged = []
    for e, i, t in out:
        if merged and abs(merged[-1][0] - e) < 0.05:
            merged[-1] = (merged[-1][0], merged[-1][1] + i, merged[-1][2])
        else:
            merged.append((e, i, t))
    return merged

def cone(r, d):
    tg = math.degrees(math.atan(r / d))
    tmax = min(tg + MARGIN_DEG, 90.0)
    return tmax, (1 - math.cos(math.radians(tg))) / 2, (1 - math.cos(math.radians(tmax))) / 2

def src_block(name, e_kev, act, z_cm, tmax):
    return f"""/gate/source/addSource {name}
/gate/source/{name}/gps/particle   gamma
/gate/source/{name}/gps/energytype Mono
/gate/source/{name}/gps/monoenergy {e_kev/1000.0:.7f} MeV
/gate/source/{name}/gps/type       Point
/gate/source/{name}/gps/centre     0 0 {z_cm:.4f} cm
/gate/source/{name}/gps/direction  0 0 -1
/gate/source/{name}/setActivity    {act:.6g} Bq
/gate/source/{name}/gps/angtype    iso
/gate/source/{name}/gps/mintheta   0 deg
/gate/source/{name}/gps/maxtheta   {tmax:.4f} deg
"""

def header(det, world_cm=120):
    vol, mat, r, h, cut = DET[det]
    return f"""# ---- GammaMAE v2 | {det} | generated by make_package.py ----
/control/verbose 0
/run/verbose 0
/event/verbose 0
/tracking/verbose 0
/gate/geometry/setMaterialDatabase @MATDB@
/gate/world/geometry/setXLength {world_cm} cm
/gate/world/geometry/setYLength {world_cm} cm
/gate/world/geometry/setZLength {world_cm} cm
/gate/world/setMaterial G4_AIR
/gate/world/daughters/name   {vol}
/gate/world/daughters/insert cylinder
/gate/{vol}/geometry/setRmax   {r} cm
/gate/{vol}/geometry/setHeight {h} cm
/gate/{vol}/placement/setTranslation 0 0 0 cm
/gate/{vol}/setMaterial {mat}
/gate/{vol}/attachCrystalSDnoSystem
/gate/physics/addPhysicsList emstandard_opt3
/gate/physics/Gamma/SetCutInRegion    world 1 mm
/gate/physics/Electron/SetCutInRegion world 1 mm
/gate/physics/Gamma/SetCutInRegion    {vol} {cut} mm
/gate/physics/Electron/SetCutInRegion {vol} {cut} mm
/gate/output/root/enable
/gate/output/root/setFileName        @OUTNAME@
/gate/output/root/setRootHitFlag     1
/gate/output/root/setRootSinglesFlag 0
/gate/output/root/setRootNtupleFlag  0
/gate/random/setEngineName MersenneTwister
/gate/random/setEngineSeed @SEED@
/gate/run/initialize
"""

FOOTER = """/gate/application/setTimeSlice @TSLICE@ s
/gate/application/setTimeStart @TSTART@ s
/gate/application/setTimeStop  @TSTOP@ s
/gate/application/startDAQ
"""

MU_E = np.array([100, 150, 200, 300, 400, 500, 600, 800, 1000, 1250, 1500, 2000, 3000.0])
MU_V = np.array([.169, .140, .125, .107, .0954, .0870, .0805, .0707, .0636, .0569, .0518, .0445, .0360])
def mu(e):
    return float(np.exp(np.interp(np.log(e), np.log(MU_E), np.log(MU_V))))
BKG_CHAIN = {"K40": (400.0, [("40k", 1.0)]),
             "U238": (35.0, [("226ra", 1.0), ("214pb", 1.0), ("214bi", 1.0)]),
             "Th232": (30.0, [("228ac", 1.0), ("212pb", 1.0), ("212bi", 1.0), ("208tl", 0.3594)])}
KAPPA_SIM = 3.0
BKG_R = {"NaI": 7.0, "HPGe": 5.0, "GAGG": 3.0}
BKG_ENTER_RATE = 5000.0

def bkg_lines():
    out = []
    for chain, (a, members) in BKG_CHAIN.items():
        for key, br in members:
            for e, i, t in lines(key, emin=150.0, imin=1.0, xrays=False):
                out.append((chain, key, e, i * br, a * br * i / mu(e)))
    return out

def scatter_hist(bl):
    E = np.unique(np.round(np.concatenate([np.geomspace(30, 2700, 140), [e - 0.02 for _, _, e, _, _ in bl],
                                           [e + 0.02 for _, _, e, _, _ in bl]]), 3))
    tot = np.zeros_like(E)
    for _, _, e0, _, w in bl:
        h = np.where(E < e0, (1 - np.exp(-(E / 70.0) ** 3)) / E, 0.0)
        g = np.linspace(30, e0, 4000)
        tot += w * h / np.trapezoid((1 - np.exp(-(g / 70.0) ** 3)) / g, g)
    return E, tot / tot.max()

def nchunks(enter):
    return next((T_MEAS // c for c in CHUNK_CHOICES if enter * c <= MAX_ENTER_PER_CHUNK), T_MEAS // 10)

def main():
    if os.path.exists(os.path.join(OUT, "jobs")):
        shutil.rmtree(os.path.join(OUT, "jobs"))
    os.makedirs(os.path.join(OUT, "jobs"))
    jobs, linetab, job_idx = [], [], 0
    bl = bkg_lines(); E, S = scatter_hist(bl); wl = np.array([b[4] for b in bl])
    for rep in SEEDS:
        for det in ["NaI", "GAGG", "HPGe"]:
            vol, mat, r, h, _ = DET[det]
            for dist in DISTS:
                for nuc, key in NUC.items():
                    L = lines(key); tmax, fg, fs = cone(r, dist); z = dist + h / 2.0
                    blocks = [src_block(f"L{k:02d}", e, ACT * i * fs, z, tmax) for k, (e, i, t) in enumerate(L)]
                    enter = sum(ACT * i * fg for _, i, _ in L); prim = sum(ACT * i * fs for _, i, _ in L)
                    if rep == 0 and dist == 5 and det == "NaI":
                        linetab += [dict(nuclide=nuc, sourceID=k, energy_keV=e, intensity=i, type=t) for k, (e, i, t) in enumerate(L)]
                    nch = nchunks(enter); name = f"{det}_{nuc}_d{dist:02d}_s{rep}"
                    jd = os.path.join(OUT, "jobs", name); os.makedirs(jd)
                    open(os.path.join(jd, "template.mac"), "w").write(header(det) + "".join(blocks) + FOOTER)
                    json.dump(dict(job=name, kind="source", detector=det, nuclide=nuc, distance_front_cm=dist,
                                   source_z_cm=z, seed_rep=rep, t_meas_s=T_MEAS, n_chunks=nch, chunk_s=T_MEAS // nch,
                                   cone_deg=tmax, f_sim=fs, f_geom=fg, activity_Bq=ACT, primaries_per_s=prim,
                                   entering_per_s=enter,
                                   lines=[dict(sourceID=k, energy_keV=e, intensity=i, type=t) for k, (e, i, t) in enumerate(L)]),
                              open(os.path.join(jd, "meta.json"), "w"), indent=1)
                    eline = max((x for x in L if x[2] == "g"), key=lambda x: x[1])[0]
                    jobs.append((name, nch, T_MEAS // nch, 1000003 * (rep + 1) + 1009 * job_idx, prim, enter, eline)); job_idx += 1
        for det in ["NaI", "GAGG", "HPGe"]:
            vol, mat, r, h, _ = DET[det]; R = BKG_R[det]
            frac = (2 * math.pi * r * r + 2 * math.pi * r * h) / (4 * math.pi * R * R)
            a_tot = BKG_ENTER_RATE / frac; a_lines = a_tot / (1 + KAPPA_SIM)
            blocks = []
            for k, (chain, key, e, i, w) in enumerate(bl):
                blocks.append(f"""/gate/source/addSource B{k:02d}
/gate/source/B{k:02d}/gps/particle   gamma
/gate/source/B{k:02d}/gps/energytype Mono
/gate/source/B{k:02d}/gps/monoenergy {e/1000.0:.7f} MeV
/gate/source/B{k:02d}/gps/type   Surface
/gate/source/B{k:02d}/gps/shape  Sphere
/gate/source/B{k:02d}/gps/radius {R} cm
/gate/source/B{k:02d}/gps/centre 0 0 0 cm
/gate/source/B{k:02d}/gps/angtype cos
/gate/source/B{k:02d}/setActivity {a_lines * w / wl.sum():.6g} Bq
""")
            hp = "".join(f"/gate/source/BSC/gps/histpoint {e/1000.0:.6f} {s:.6e}\n" for e, s in zip(E, S))
            blocks.append(f"""/gate/source/addSource BSC
/gate/source/BSC/gps/particle   gamma
/gate/source/BSC/gps/energytype Arb
/gate/source/BSC/gps/histname   arb
/gate/source/BSC/gps/emin 0.030 MeV
/gate/source/BSC/gps/emax 2.700 MeV
{hp}/gate/source/BSC/gps/arbint Lin
/gate/source/BSC/gps/type   Surface
/gate/source/BSC/gps/shape  Sphere
/gate/source/BSC/gps/radius {R} cm
/gate/source/BSC/gps/centre 0 0 0 cm
/gate/source/BSC/gps/angtype cos
/gate/source/BSC/setActivity {a_tot - a_lines:.6g} Bq
""")
            nch = nchunks(BKG_ENTER_RATE); name = f"{det}_BKG_s{rep}"
            jd = os.path.join(OUT, "jobs", name); os.makedirs(jd)
            open(os.path.join(jd, "template.mac"), "w").write(header(det) + "".join(blocks) + FOOTER)
            json.dump(dict(job=name, kind="background", detector=det, seed_rep=rep, t_meas_s=T_MEAS, n_chunks=nch,
                           chunk_s=T_MEAS // nch, sphere_R_cm=R, hit_fraction_expected=frac, primaries_per_s=a_tot,
                           entering_per_s=BKG_ENTER_RATE, kappa_sim=KAPPA_SIM,
                           note="activities are NOT physical; background is re-sampled to a target rate in post-processing",
                           lines=[dict(sourceID=j, chain=c, nuclide=kk, energy_keV=e, intensity_eff=i, flux_weight=float(w / wl.sum()))
                                  for j, (c, kk, e, i, w) in enumerate(bl)] +
                                 [dict(sourceID=len(bl), chain="scatter", nuclide="continuum", energy_keV=None)]),
                      open(os.path.join(jd, "meta.json"), "w"), indent=1)
            jobs.append((name, nch, T_MEAS // nch, 1000003 * (rep + 1) + 1009 * job_idx, a_tot, BKG_ENTER_RATE, 1460.82)); job_idx += 1
    jobs.sort(key=lambda j: {"NaI_Cs137_d10_s0": 0, "NaI_BKG_s0": 1}.get(j[0], 2))
    with open(os.path.join(OUT, "jobs.tsv"), "w") as fh:
        fh.write("job\tn_chunks\tchunk_s\tseed_base\tprimaries_per_s\tentering_per_s\tcheck_line_keV\n")
        for j in jobs:
            fh.write(f"{j[0]}\t{j[1]}\t{j[2]}\t{j[3]}\t{j[4]:.1f}\t{j[5]:.1f}\t{j[6]:.3f}\n")
    pd.DataFrame(linetab).to_csv(os.path.join(OUT, "source_lines.csv"), index=False)
    pd.DataFrame([dict(chain=c, nuclide=k, energy_keV=e, intensity_eff=i, flux_weight=w / wl.sum())
                  for c, k, e, i, w in bl]).to_csv(os.path.join(OUT, "background_lines.csv"), index=False)
    P = sum(j[4] * T_MEAS for j in jobs); N = sum(j[5] * T_MEAS for j in jobs)
    print(f"jobs={len(jobs)} primaries={P:.3e} entering={N:.3e} chunks={sum(j[1] for j in jobs)}")

if __name__ == "__main__":
    main()
